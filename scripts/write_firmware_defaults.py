"""Generate the shared defaults from the selected reference profile."""
import json
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path
from calibrate import FIELDS

ROOT = Path(__file__).resolve().parents[1]


def write_defaults():
    data = json.loads((ROOT/'calibration/firmware_defaults.json').read_text())
    profile = data['calibration']
    reference = data['reference']
    fraction = Decimal(str(data['fraction']))
    for axis in ('x', 'y'):
        center = reference[f'{axis}_center']
        assert profile[f'{axis}_center'] == center
        for edge in ('min', 'max'):
            value = Decimal(center) + fraction * Decimal(reference[f'{axis}_{edge}'] - center)
            assert profile[f'{axis}_{edge}'] == int(value.quantize(Decimal(1), rounding=ROUND_HALF_UP))
    values = ', '.join(str(profile[k]) for k in FIELDS)
    header = ('// Generated by scripts/write_firmware_defaults.py.\n'
              '// Aftermarket #2: 75% of each center-to-endpoint distance.\n'
              '// Shared early saturation; optional EEPROM calibration overrides these.\n'
              '#pragma once\n'
              f'#define VECTREX_STOCK_CALIBRATION_VALUES {values}\n')
    (ROOT/'firmware/common/stock_defaults.h').write_text(header)
    print(data['name'] + ': ' + values)


if __name__ == '__main__':
    write_defaults()
